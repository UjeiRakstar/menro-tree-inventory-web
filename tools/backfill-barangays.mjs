/**
 * Works out each tree's barangay from its coordinates, and writes the SQL.
 *
 *   node tools/backfill-barangays.mjs
 *
 * This is the one-off that settles the rows supabase/barangay_link.sql cannot:
 * the names that more than one town shares ("San Jose" is a barangay of
 * several), and the ones that match nothing at all. A coordinate answers both.
 *
 * It only READS from Supabase, with the same public key the website uses, and
 * it writes nothing to the database. What it produces is a file of UPDATE
 * statements at supabase/barangay_backfill.sql for you to read and then run
 * yourself — because a script that silently rewrites 112 rows of field data is
 * not something to run on trust.
 *
 * Needs VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY, which are already in
 * your .env.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

/** Read .env without a dependency; it is four lines of KEY=value. */
async function readEnv() {
  const env = { ...process.env };
  try {
    const text = await readFile(join(root, '.env'), 'utf8');
    for (const line of text.split(/\r?\n/)) {
      const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/i);
      if (match) env[match[1]] ??= match[2].replace(/^["']|["']$/g, '');
    }
  } catch {
    // No .env; the variables may be in the environment already.
  }
  return env;
}

const env = await readEnv();
const url = env.VITE_SUPABASE_URL;
const key = env.VITE_SUPABASE_ANON_KEY;
if (!url || !key) {
  console.error('VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY must be set (they are in .env).');
  process.exit(1);
}

const index = JSON.parse(await readFile(join(root, 'src', 'data', 'barangay-index.json'), 'utf8'));

function inRing(flat, x, y) {
  let inside = false;
  for (let i = 0, j = flat.length - 2; i < flat.length; j = i, i += 2) {
    const xi = flat[i];
    const yi = flat[i + 1];
    const xj = flat[j];
    const yj = flat[j + 1];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function inShape(shape, x, y) {
  for (const polygon of shape) {
    if (!inRing(polygon[0], x, y)) continue;
    let inHole = false;
    for (let i = 1; i < polygon.length; i += 1) {
      if (inRing(polygon[i], x, y)) {
        inHole = true;
        break;
      }
    }
    if (!inHole) return true;
  }
  return false;
}

function barangayAt(lat, lng) {
  for (const barangay of index.barangays) {
    const [minX, minY, maxX, maxY] = barangay.b;
    if (lng < minX || lng > maxX || lat < minY || lat > maxY) continue;
    if (inShape(barangay.g, lng, lat)) return barangay;
  }
  return null;
}

// Read the inventory. Only the four columns this needs.
const response = await fetch(
  `${url}/rest/v1/trees?select=id,barangay,latitude,longitude&limit=10000`,
  { headers: { apikey: key, Authorization: `Bearer ${key}` } }
);
if (!response.ok) {
  console.error(`Could not read the inventory: ${response.status} ${await response.text()}`);
  process.exit(1);
}
const trees = await response.json();

const quote = (text) => `'${String(text).replace(/'/g, "''")}'`;

const updates = [];
const unplaceable = [];
let unchanged = 0;

for (const tree of trees) {
  const lat = Number(tree.latitude);
  const lng = Number(tree.longitude);
  if (!Number.isFinite(lat) || !Number.isFinite(lng) || (lat === 0 && lng === 0)) {
    unplaceable.push({ ...tree, why: 'no usable coordinates' });
    continue;
  }
  const found = barangayAt(lat, lng);
  if (!found) {
    unplaceable.push({ ...tree, why: 'falls outside every barangay in Laguna' });
    continue;
  }
  if ((tree.barangay || '').trim() === found.n) {
    unchanged += 1;
    continue;
  }
  updates.push({ id: tree.id, from: tree.barangay, to: found.n, lgu: found.m, psgc: found.p });
}

const lines = updates.map(
  (u) =>
    `update public.trees set barangay_psgc = ${u.psgc} where id = ${quote(u.id)};` +
    `  -- ${u.lgu}: ${JSON.stringify(u.from ?? null)} -> ${u.to}`
);

const sql = `-- Green Tag: each tree's barangay, from where it stands.
--
-- GENERATED by tools/backfill-barangays.mjs on ${new Date().toISOString().slice(0, 10)}.
-- Read it before running it. Every line says what it is changing and why.
--
-- Run AFTER supabase/barangays.sql and supabase/barangay_link.sql: only the
-- PSGC code is set here, and the trigger from barangay_link fills the name
-- from the reference table, so the two can never disagree.
--
-- ${trees.length} trees read. ${updates.length} to correct, ${unchanged} already right, ${unplaceable.length} that coordinates cannot place.

${lines.join('\n') || '-- Nothing to correct.'}

${
  unplaceable.length
    ? `-- ---------------------------------------------------------------------------
-- Not touched — these need a person, not a query.
-- ---------------------------------------------------------------------------
${unplaceable.map((t) => `--   ${t.id}  (${t.barangay ?? 'no barangay'})  ${t.why}`).join('\n')}`
    : '-- Every tree could be placed.'
}

-- What it looks like afterwards.
select
  coalesce(b.name, nullif(trim(t.barangay), ''), '(not recorded)') as barangay,
  coalesce(b.municipality, '(unplaced)') as municipality,
  count(*) as trees
from public.trees t
left join public.barangays b on b.psgc = t.barangay_psgc
group by 1, 2
order by 2, 1;
`;

await writeFile(join(root, 'supabase', 'barangay_backfill.sql'), sql);

console.log(`${trees.length} trees read.`);
console.log(`  ${updates.length} to correct`);
console.log(`  ${unchanged} already right`);
console.log(`  ${unplaceable.length} that coordinates cannot place`);
for (const tree of unplaceable) console.log(`    ${tree.id}: ${tree.why}`);
console.log('\nWritten to supabase/barangay_backfill.sql — read it, then run it.');
