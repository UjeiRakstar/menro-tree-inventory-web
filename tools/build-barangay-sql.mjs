/**
 * Writes supabase/barangays.sql from the boundary data.
 *
 *   node tools/build-barangay-sql.mjs
 *
 * The reference table is generated rather than typed, so the names in the
 * database, the names in the web app and the names in the field app all come
 * from the one PSA/NAMRIA source and cannot drift apart.
 *
 * The output is committed; re-run it only if the boundaries change.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(here, '..', 'src', 'data', 'Laguna-Barangays.geojson');
const OUT = join(here, '..', 'supabase', 'barangays.sql');

/** Single quotes are the only thing that can break out of a SQL literal. */
const quote = (text) => `'${String(text).replace(/'/g, "''")}'`;

const geojson = JSON.parse(await readFile(SOURCE, 'utf8'));

const rows = geojson.features
  .map((f) => f.properties)
  .map((p) => ({
    psgc: p.barangay_psgc,
    name: p.barangay,
    municipality: p.municipality,
    municipalityLabel: p.municipality_label,
    municipalityPsgc: p.municipality_psgc,
    isCity: p.is_city,
  }))
  .sort((a, b) => a.municipality.localeCompare(b.municipality) || a.name.localeCompare(b.name));

const values = rows
  .map(
    (r) =>
      `  (${r.psgc}, ${quote(r.name)}, ${quote(r.municipality)}, ` +
      `${quote(r.municipalityLabel)}, ${r.municipalityPsgc}, ${r.isCity})`
  )
  .join(',\n');

const lgus = new Set(rows.map((r) => r.municipality));

const sql = `-- Green Tag: the barangays of Laguna, as the PSA names them.
--
-- GENERATED by tools/build-barangay-sql.mjs from src/data/Laguna-Barangays.geojson.
-- Do not edit by hand: re-run the tool instead, so the database, the web app
-- and the field app keep taking their names from the one source.
--
-- WHY THIS TABLE EXISTS
-- public.trees.barangay is free text, filled by the field app from a reverse
-- geocode against OpenStreetMap. OSM answers with whatever a mapper tagged, so
-- the column collected subdivision names ("Villa Silangan Subdivision"),
-- placeholders ("Unknown Barangay"), and names stripped of the word Barangay
-- until they named nothing ("V"). Nothing rejected any of it.
--
-- This is the list to check against. ${rows.length} barangays across ${lgus.size} cities and
-- municipalities, each with its PSGC code.
--
-- Running this twice is harmless.

create table if not exists public.barangays (
  psgc               bigint primary key,
  name               text    not null,
  municipality       text    not null,
  municipality_label text    not null,
  municipality_psgc  bigint  not null,
  is_city            boolean not null default false,
  unique (municipality, name)
);

comment on table public.barangays is
  'The barangays of Laguna as the PSA names them. Generated from the NAMRIA/PSA boundaries; see tools/build-barangay-sql.mjs.';

insert into public.barangays
  (psgc, name, municipality, municipality_label, municipality_psgc, is_city)
values
${values}
on conflict (psgc) do update
  set name               = excluded.name,
      municipality       = excluded.municipality,
      municipality_label = excluded.municipality_label,
      municipality_psgc  = excluded.municipality_psgc,
      is_city            = excluded.is_city;

-- Anyone may read the list. It is public information, and the tagging form
-- needs it to offer a barangay to choose from.
alter table public.barangays enable row level security;

do $$
begin
  create policy "anyone reads the barangay list" on public.barangays
    for select to anon, authenticated using (true);
exception
  when duplicate_object then null;
end;
$$;

-- ---------------------------------------------------------------------------
-- What the inventory looks like against the list.
--
-- \`reads_as\` is the thing to read. Anything that is not 'official' is a name
-- no barangay in Laguna has, which means nobody can group it, map it or count
-- it -- and the tree is still somewhere, so it is worth chasing.
-- ---------------------------------------------------------------------------
select
  coalesce(nullif(trim(t.barangay), ''), '(not recorded)') as written,
  count(*) as trees,
  case
    when t.barangay is null or trim(t.barangay) = '' then 'not recorded'
    when exists (
      select 1 from public.barangays b
      where lower(b.name) = lower(trim(t.barangay))
    ) then 'official'
    when exists (
      select 1 from public.barangays b
      where lower(b.name) = lower('Barangay ' || trim(t.barangay))
    ) then 'official, missing the word Barangay'
    when t.barangay ~* '^(unknown|n/?a)' then 'placeholder'
    else 'no barangay of this name in Laguna'
  end as reads_as
from public.trees t
group by 1, 3
order by 3, 1;
`;

await writeFile(OUT, sql);
console.log(`${rows.length} barangays across ${lgus.size} LGUs -> supabase/barangays.sql`);
